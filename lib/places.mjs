for (const x of 世界表) 地点反查.set(x.名, x.类)

/** 词 → 类别（国家/地区/组织），不是则 null */
export function 查地点(词) {
  return 地点反查.get(String(词 || '').trim()) || null
}

/** 按类别分组，给面板「世界」页签用 */
export function 世界分组() {
  const 类序 = ['世界', '国家', '地区', '组织']
  return 类序.map((类) => ({
    类,
    items: 世界表.filter((x) => x.类 === 类).map((x) => x.名),
  }))
}
