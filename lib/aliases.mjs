// 别名 → 正名（用于精确命中）
const 反查 = new Map()
for (const e of 别名表) {
  for (const a of e.别) {
    if (!反查.has(a)) 反查.set(a, e.名)
  }
}

/**
 * 解析查询里的别名。
 *   精确命中（整个词就是别名）→ 整体换成正名
 *   包含命中（长句里带别名）  → 只替换那一段
 * 返回 { 命中, 原名, 正式, 列表: [{别, 正式}] }
 */
export function 解析别名(词) {
  const 原 = String(词 || '').trim()
  const 空 = { 命中: false, 原名: 原, 正式: 原, 列表: [] }
  if (!原) return 空

  const 直接 = 反查.get(原)
  if (直接) return { 命中: true, 原名: 原, 正式: 直接, 列表: [{ 别: 原, 正式: 直接 }] }

  // 长句：按别名长度从长到短替换，避免「大爹」先吃掉「大爹们」之类
  const 条目 = [...反查.entries()].sort((a, b) => b[0].length - a[0].length)
  let 结果 = 原
  const 换过 = []
  for (const [别, 正式] of 条目) {
    if (!结果.includes(别)) continue
    if (结果.includes(正式)) continue
    结果 = 结果.split(别).join(正式)
    换过.push({ 别, 正式 })
  }
  if (换过.length === 0) return 空
  return { 命中: true, 原名: 原, 正式: 结果, 列表: 换过 }
}

/** 给 UI 用的一句话：如「兔兔 → 阿米娅」 */
export function 别名说明(列表) {
  return (列表 || []).map((x) => `${x.别} → ${x.正式}`).join('、')
}
