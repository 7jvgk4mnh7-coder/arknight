/**
 * aliases.mjs —— 别名表：真名、称呼、常见外号 → 剧情里用的正式名
 *
 * 只收「指向明确」的别名；像「殿下」这种可能指好几个人的，宁可不收。
 * 表是纯数据，想加就改这里（改完重启宿主即可）。
 *
 * 注意：别名只是把查询换成正名，搜索时**原名和正名都会搜**，所以不会丢结果。
 */

